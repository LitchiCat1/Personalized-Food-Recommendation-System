"""Persist the server-owned scan snapshot produced by vision recognition.

The vision response contains presentation-only fields (alternatives, bounding
boxes and free-form visual notes).  Enrichment authorization must be based on
the smaller, repository-owned item contract instead of copying that response
or trusting a later client request.
"""

from copy import deepcopy

from repositories.scan_context_repository import ScanContextRepositoryError


_ITEM_FIELDS = (
    "item_id", "item_revision", "name_zh", "confidence", "weight_confidence",
    "estimated_weight_g", "food_state", "preparation_method", "components_scope",
    "brand", "variant", "validation_issues",
)


class NutritionScanContextAdapterError(ValueError):
    """Typed adapter error; the legacy vision route can fail closed when enabled."""

    def __init__(self, code, message):
        self.code = code
        super().__init__(message)


def _fail(code, message):
    raise NutritionScanContextAdapterError(code, message)


def _server_item(item):
    if not isinstance(item, dict):
        _fail("invalid_context", "Vision recognition item is invalid")
    # The response was generated by the server, but make the boundary explicit
    # so future response fields cannot silently become authority claims.
    return {field: deepcopy(item.get(field)) for field in _ITEM_FIELDS}


def build_scan_context_items(response):
    """Return only the repository-approved item fields from a vision response."""
    if not isinstance(response, dict):
        _fail("invalid_context", "Vision recognition response is invalid")
    recognition = response.get("recognition_context")
    if not isinstance(recognition, dict):
        _fail("invalid_context", "Vision recognition context is missing")
    source_items = recognition.get("items")
    if not isinstance(source_items, list):
        _fail("invalid_context", "Vision recognition items are missing")
    return [_server_item(item) for item in source_items]


def persist_vision_scan_context(response, *, user_id, repository, ttl_seconds=120):
    """Persist one complete server-owned scan context.

    Empty recognition results do not create a context because the repository
    intentionally requires at least one item.  The returned document is the
    repository result, making idempotent scanner retries observable to callers.
    """
    if not isinstance(user_id, str) or not user_id.strip():
        return None
    if repository is None or not hasattr(repository, "save_scan_context"):
        _fail("storage_unavailable", "Scan context storage is unavailable")
    scan_id = response.get("scan_id") if isinstance(response, dict) else None
    scan_revision = response.get("scan_revision", 0) if isinstance(response, dict) else None
    if not isinstance(scan_id, str) or not scan_id.strip():
        _fail("invalid_context", "Server scan_id is missing")
    items = build_scan_context_items(response)
    if not items:
        return None
    try:
        return repository.save_scan_context(
            user_id=user_id,
            scan_id=scan_id,
            scan_revision=scan_revision,
            items=items,
            ttl_seconds=ttl_seconds,
        )
    except ScanContextRepositoryError as error:
        raise NutritionScanContextAdapterError(error.code, str(error)) from error


__all__ = [
    "NutritionScanContextAdapterError",
    "build_scan_context_items",
    "persist_vision_scan_context",
]
